// Wavefront OBJ import/export (collision import, KCL export, generated track model export).

import { KCL_TYPES } from '../data/defs.js';

// Parses an OBJ file into triangle lists grouped by material.
export function parseOBJ(text) {
  const pos = [], uvs = [];
  const groups = new Map(); // material -> number[]
  let current = 'default';
  const vertex = (tok) => {
    const i = parseInt(tok.split('/')[0], 10);
    return pos[i < 0 ? pos.length + i : i - 1];
  };
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line[0] === '#') continue;
    const parts = line.split(/\s+/);
    switch (parts[0]) {
      case 'v': pos.push([+parts[1], +parts[2], +parts[3]]); break;
      case 'vt': uvs.push([+parts[1], +parts[2]]); break;
      case 'usemtl': current = parts.slice(1).join(' ') || 'default'; break;
      case 'f': {
        const vs = parts.slice(1).map(vertex);
        if (vs.some((v) => !v)) break;
        let arr = groups.get(current);
        if (!arr) groups.set(current, (arr = []));
        for (let i = 1; i + 1 < vs.length; i++) arr.push(...vs[0], ...vs[i], ...vs[i + 1]); // fan triangulation
        break;
      }
    }
  }
  return [...groups].map(([material, v]) => ({ material, verts: Float32Array.from(v) }));
}

// Guesses a KCL flag from a material name (hex flag like "0x000C" / "_000C", or keywords).
export function guessFlag(material) {
  const m = material.match(/0x([0-9a-f]{1,4})/i) || material.match(/(?:^|_)([0-9a-f]{4})$/i);
  if (m) return parseInt(m[1], 16);
  const n = material.toLowerCase();
  const rules = [
    [/fall|death|void|kill/, 0x10], [/invis/, 0x0D], [/wall|fence|rail|barrier/, 0x0C],
    [/boost|dash/, 0x06], [/ramp/, 0x07], [/jump|spring/, 0x08], [/heavy|deep/, 0x04],
    [/offroad|off_road|grass|dirt|sand|mud/, 0x03], [/ice|slip/, 0x01], [/water/, 0x0B],
    [/lava/, 0x0A], [/cannon/, 0x11], [/halfpipe|half_pipe/, 0x13],
  ];
  for (const [re, f] of rules) if (re.test(n)) return f;
  return 0x00;
}

// Exports collision triangles as OBJ, one material per flag (re-importable with guessFlag).
export function kclToOBJ(kcl) {
  const byFlag = new Map();
  for (let t = 0; t < kcl.count; t++) {
    if (kcl.valid && !kcl.valid[t]) continue;
    const f = kcl.flags[t];
    if (!byFlag.has(f)) byFlag.set(f, []);
    byFlag.get(f).push(t);
  }
  const lines = ['# Exported by MKWii Advanced Editor', 'mtllib collision.mtl'];
  const mtl = [];
  let vi = 1;
  for (const [flag, tris] of byFlag) {
    const type = KCL_TYPES[flag & 0x1F];
    const name = `kcl_0x${flag.toString(16).padStart(4, '0').toUpperCase()}_${type.name.replace(/[^a-z0-9]+/gi, '_')}`;
    const c = hexToRgb(type.color);
    mtl.push(`newmtl ${name}`, `Kd ${c.join(' ')}`, '');
    lines.push(`o ${name}`, `usemtl ${name}`);
    for (const t of tris) {
      for (let k = 0; k < 3; k++) lines.push(`v ${kcl.verts[t * 9 + k * 3]} ${kcl.verts[t * 9 + k * 3 + 1]} ${kcl.verts[t * 9 + k * 3 + 2]}`);
      lines.push(`f ${vi} ${vi + 1} ${vi + 2}`);
      vi += 3;
    }
  }
  return { obj: lines.join('\n') + '\n', mtl: mtl.join('\n') };
}

// Exports a generated model ({ tris: [{ mat, v, uv }], materials }) as OBJ + MTL.
export function modelToOBJ(model, mtlName = 'course_model.mtl') {
  const lines = ['# Track model generated by MKWii Advanced Editor', `mtllib ${mtlName}`];
  const mtl = [];
  const byMat = new Map();
  for (const t of model.tris) {
    if (!byMat.has(t.mat)) byMat.set(t.mat, []);
    byMat.get(t.mat).push(t);
  }
  let vi = 1;
  for (const [mat, tris] of byMat) {
    const c = model.materials[mat]?.color || [0.7, 0.7, 0.7];
    mtl.push(`newmtl ${mat}`, `Kd ${c.join(' ')}`, `# map_Kd ${mat}.png`, '');
    lines.push(`o ${mat}`, `usemtl ${mat}`);
    for (const t of tris) {
      for (let k = 0; k < 3; k++) lines.push(`v ${t.v[k * 3]} ${t.v[k * 3 + 1]} ${t.v[k * 3 + 2]}`);
      for (let k = 0; k < 3; k++) lines.push(`vt ${t.uv?.[k * 2] ?? 0} ${t.uv?.[k * 2 + 1] ?? 0}`);
      lines.push(`f ${vi}/${vi} ${vi + 1}/${vi + 1} ${vi + 2}/${vi + 2}`);
      vi += 3;
    }
  }
  return { obj: lines.join('\n') + '\n', mtl: mtl.join('\n') };
}

function hexToRgb(hex) {
  const v = parseInt(hex.slice(1), 16);
  return [((v >> 16) & 255) / 255, ((v >> 8) & 255) / 255, (v & 255) / 255].map((x) => x.toFixed(3));
}
