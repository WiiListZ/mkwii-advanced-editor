// Bundles the UI (web/) into dist/ and generates src/embedded.gen.ts,
// the list of files served by the server (embedded into the executable by --compile).

import { readdir, rm, mkdir, copyFile, stat } from "node:fs/promises";
import { join, relative } from "node:path";

const root = join(import.meta.dir, "..");
const dist = join(root, "dist");
const minify = process.argv.includes("--release");

await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });

const result = await Bun.build({
  entrypoints: [join(root, "web/src/main.tsx")],
  outdir: dist,
  target: "browser",
  naming: "app.js",
  minify,
  sourcemap: minify ? "none" : "linked",
  define: { "process.env.NODE_ENV": JSON.stringify(minify ? "production" : "development") },
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}

// Tailwind CSS (shadcn/ui theme) -> dist/style.css
const tailwind = join(root, "node_modules/.bin", process.platform === "win32" ? "tailwindcss.exe" : "tailwindcss");
const css = Bun.spawn([tailwind, "-i", join(root, "web/src/index.css"), "-o", join(dist, "style.css"), ...(minify ? ["--minify"] : [])], { cwd: root, stdout: "pipe", stderr: "pipe" });
if ((await css.exited) !== 0) {
  console.error(await new Response(css.stderr).text());
  process.exit(1);
}

await copyFile(join(root, "web/index.html"), join(dist, "index.html"));
await copyFile(join(root, "web/icon.png"), join(dist, "icon.png"));

// "Mario Kart Wii" interface font (M PLUS 1, OFL): Latin subsets only, with its license.
const font = join(root, "node_modules/@fontsource-variable/m-plus-1");
await mkdir(join(dist, "fonts"), { recursive: true });
for (const subset of ["latin", "latin-ext"]) await copyFile(join(font, "files", `m-plus-1-${subset}-wght-normal.woff2`), join(dist, "fonts", `m-plus-1-${subset}-wght-normal.woff2`));
await copyFile(join(font, "LICENSE"), join(dist, "fonts", "OFL.txt"));

// The bzip2 decoder is bundled into the one-file executable; keep its MIT notice with it.
await mkdir(join(dist, "licenses"), { recursive: true });
await copyFile(join(root, "node_modules", "seek-bzip", "LICENSE"), join(dist, "licenses", "seek-bzip.txt"));
await copyFile(join(root, "node_modules", "fflate", "LICENSE"), join(dist, "licenses", "fflate.txt"));
await copyFile(join(root, "node_modules", "@breezystack", "lamejs", "LICENSE"), join(dist, "licenses", "lamejs.txt"));

// Pulsar engine files (MIT), written into a new mod when custom cups are created; see vendor/pulsar/NOTICE.md.
await mkdir(join(dist, "pulsar"), { recursive: true });
for (const f of await readdir(join(root, "vendor", "pulsar"))) await copyFile(join(root, "vendor", "pulsar", f), join(dist, "pulsar", f));

const entries = await readdir(dist, { recursive: true });
const files = (await Promise.all(entries.map(async (f) => (await stat(join(dist, f))).isFile() ? relative(dist, join(dist, f)).replace(/\\/g, "/") : null))).filter((f): f is string => !!f);
const lines = [
  "// Generated by scripts/build-frontend.ts - do not edit by hand.",
  ...files.map((f, i) => `import f${i} from "../dist/${f}" with { type: "file" };`),
  "export const assets: Record<string, string> = {",
  ...files.map((f, i) => `  ${JSON.stringify(f)}: f${i},`),
  "};",
  "",
];
await Bun.write(join(root, "src/embedded.gen.ts"), lines.join("\n"));
console.log(`UI built: ${files.length} files in dist/`);
