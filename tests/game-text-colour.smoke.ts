// Edits/saves colours only in a temporary BMG fixture, with real game layouts and fonts.
// MKWII_GAME_DIR=<extracted files> bun tests/game-text-colour.smoke.ts
import puppeteer from 'puppeteer-core';
import { copyFileSync, mkdirSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, sep } from 'node:path';
import { bmgColourCode } from '../web/js/formats/bmg-style.js';
import { createBMG, parseBMG, setFontSizePercent } from '../web/js/formats/bmg.js';
import { buildU8, findFile, newSzsTree, parseU8, setFilePath } from '../web/js/formats/u8.js';
import { yaz0Decompress } from '../web/js/formats/yaz0.js';

const game = process.env.MKWII_GAME_DIR;
if (!game) throw Error('Set MKWII_GAME_DIR to the extracted game files');
const temp = mkdtempSync(join(tmpdir(), 'mkwii-text-colour-')), files = join(temp, 'files'), ui = join(files, 'Scene', 'UI');
mkdirSync(ui, { recursive: true }); mkdirSync(join(files, 'Race', 'Course'), { recursive: true });
for (const name of ['MenuSingle.szs', 'Race.szs', 'Font.szs']) copyFileSync(join(game, 'Scene/UI', name), join(ui, name));
const fixture = newSzsTree(), archive = join(ui, 'MenuSingle_E.szs');
setFilePath(fixture, 'message/Common.bmg', createBMG([[0x245c, 'Luigi Circuit'], [0x2455, 'Moo Moo Meadows']]));
setFilePath(fixture, 'message/Menu.bmg', createBMG([[0x7d1, 'Back']]));
await Bun.write(archive, buildU8(fixture));
await Bun.write(join(temp, 'settings.json'), JSON.stringify({ tourDone: true, discordActivity: false, workspace: files, keepBackups: false }));
const worker = new Worker(new URL('../src/server.ts', import.meta.url).href);
let browser: Awaited<ReturnType<typeof puppeteer.launch>> | null = null;
const check = (ok: unknown, text: string) => { if (!ok) throw Error(text); console.log('ok: ' + text); };
try {
  const port = await new Promise<number>((done) => { worker.onmessage = (e) => e.data?.type === 'ready' && done(e.data.port); worker.postMessage({ type: 'start', token: 'colours', settingsDir: temp }); });
  browser = await puppeteer.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage(), errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.setViewport({ width: 1500, height: 1000 });
  await page.goto(`http://127.0.0.1:${port}/?t=colours`, { waitUntil: 'networkidle0' });
  await page.evaluate(() => { void (window as any).app.cmd('gameText'); });
  await page.waitForSelector('textarea[aria-label="Message text"]:not([disabled])');
  const setText = async (selector: string, text: string) => page.$eval(selector, (el, text) => {
    const proto = el.tagName === 'TEXTAREA' ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype;
    Object.getOwnPropertyDescriptor(proto, 'value')!.set!.call(el, text); el.dispatchEvent(new Event('input', { bubbles: true }));
  }, text);
  await setText('input[placeholder^="Find text"]', '0x245c');
  await page.waitForFunction(() => document.body.innerText.includes('Common.bmg · 0x245C'));
  await page.waitForSelector('canvas[data-preview-state="screen"]');
  const area = 'textarea[aria-label="Message text"]';
  const value = () => page.$eval(area, (el) => (el as HTMLTextAreaElement).value);
  const shortcut = async (key: string) => { await page.keyboard.down('Control'); await page.keyboard.press(key); await page.keyboard.up('Control'); };
  const choose = async (label: string) => {
    await page.evaluate(() => { ([...document.querySelectorAll('button')].find((b) => b.textContent?.trim() === 'Text colour') as HTMLElement).click(); });
    await page.waitForSelector(`button[aria-label="Text colour: ${label}"]`);
    await page.click(`button[aria-label="Text colour: ${label}"]`);
    await page.waitForSelector(`button[aria-label="Text colour: ${label}"]`, { hidden: true });
    await page.waitForFunction(() => document.activeElement?.getAttribute('aria-label') === 'Message text');
  };
  await page.focus(area); await shortcut('a'); await page.keyboard.type('Road');
  check(await value() === 'Road', 'typing replaces the selected text');
  await setText('input[placeholder^="Find text"]', 'Road');
  await page.focus(area);
  await shortcut('z'); check(await value() === 'Luigi Circuit', 'Ctrl+Z groups consecutive typing and keeps the restored message visible through filters');
  await page.keyboard.down('Control'); await page.keyboard.down('Shift'); await page.keyboard.press('z'); await page.keyboard.up('Shift'); await page.keyboard.up('Control');
  check(await value() === 'Road', 'Ctrl+Shift+Z also redoes typing');
  await shortcut('z');
  await choose('Red');
  check(await value() === bmgColourCode(0x32) + 'Luigi Circuit', 'whole-message picker inserts a native BMG colour');
  await choose('Blue');
  check(await value() === bmgColourCode(0x31) + 'Luigi Circuit', 'recolouring replaces the old tag without accumulating codes');
  await page.$eval(area, (el, prefix) => { const t = el as HTMLTextAreaElement; t.focus(); t.setSelectionRange(prefix, prefix + 5); }, bmgColourCode(0x31).length);
  await choose('Yellow');
  check(await value() === bmgColourCode(0x30) + 'Luigi' + bmgColourCode(0x31) + ' Circuit', 'selected word changes colour while the rest keeps its original colour');
  const styled = await value(), cutValue = bmgColourCode(0x30) + bmgColourCode(0x31) + ' Circuit';
  await shortcut('x');
  check(await value() === cutValue, 'Ctrl+X cuts the selected word without breaking surrounding BMG codes');
  await shortcut('v');
  check(await value() === styled, 'the cut word can be pasted back from the clipboard');
  await shortcut('z'); check(await value() === cutValue, 'Ctrl+Z undoes paste');
  await shortcut('z'); check(await value() === styled, 'Ctrl+Z undoes cut');
  await shortcut('y'); check(await value() === cutValue, 'Ctrl+Y redoes cut');
  await shortcut('y'); check(await value() === styled, 'Ctrl+Y redoes paste');
  await shortcut('z'); await shortcut('z'); await shortcut('z');
  check(await value() === bmgColourCode(0x31) + 'Luigi Circuit', 'colour changes share the same undo history as typing and clipboard edits');
  await shortcut('y'); check(await value() === styled, 'Ctrl+Y restores the selected-word colour');
  await page.screenshot({ path: '.cache/text-colour-selection.png' });
  await page.$eval(area, (el) => (el as HTMLTextAreaElement).setSelectionRange(0, 0));
  await choose('Default (layout)');
  check(await value() === 'Luigi Circuit', 'default restores the layout colour and removes colour tags');
  await choose('Red');
  await page.evaluate(() => { ([...document.querySelectorAll('button')].find((b) => b.textContent?.trim() === 'Text colour') as HTMLElement).click(); });
  await page.waitForSelector('[data-text-colours]');
  await page.hover('button[aria-label="Text colour: Blue"]');
  await new Promise((done) => setTimeout(done, 500));
  check(!!await page.$('[data-text-colours]') && !await page.$('[role="tooltip"]') && await page.$$eval('[data-text-colours] [title]', (els) => !els.length), 'the colour palette has no custom or native tooltips');
  await page.focus('button[aria-label="Text colour: Blue"]');
  await shortcut('z');
  check(await value() === 'Luigi Circuit', 'Ctrl+Z also works with the palette open');
  await shortcut('y');
  check(await value() === bmgColourCode(0x32) + 'Luigi Circuit', 'Ctrl+Y restores the colour after the palette closes');
  await page.$eval(area, (el) => (el as HTMLTextAreaElement).setSelectionRange(0, 0)); await choose('Default (layout)');
  await choose('Red');
  await setText('input[placeholder^="Find text"]', '0x2455');
  await page.waitForFunction(() => document.body.innerText.includes('Common.bmg · 0x2455'));
  await choose('Blue');
  await shortcut('z'); check(await value() === 'Moo Moo Meadows', 'undo restores the current message');
  await shortcut('z');
  await page.waitForFunction(() => document.body.innerText.includes('Common.bmg · 0x245C'));
  check(await value() === 'Luigi Circuit', 'undo also restores a previous message and its selection');
  await shortcut('y'); check(await value() === bmgColourCode(0x32) + 'Luigi Circuit', 'redo restores the previous message formatting');
  await shortcut('y');
  await page.waitForFunction(() => document.body.innerText.includes('Common.bmg · 0x2455'));
  check(await value() === bmgColourCode(0x31) + 'Moo Moo Meadows', 'redo follows edits across messages');
  await shortcut('z');
  await setText('input[placeholder^="Find text"]', '0x245c');
  await page.waitForFunction(() => document.body.innerText.includes('Common.bmg · 0x245C'));
  await page.$eval(area, (el) => (el as HTMLTextAreaElement).setSelectionRange(0, 0)); await choose('Default (layout)');
  await setText(area, 'A'.repeat(32));
  await page.$eval(area, (el) => (el as HTMLTextAreaElement).setSelectionRange(0, 0));
  await choose('Red');
  check(await value() === 'A'.repeat(32), 'a colour that exceeds the actual buffer is rejected without losing text');
  check(await page.$eval('#game-text-error', (el) => el.textContent?.includes('32 characters')), 'the native-capacity error explains why the colour cannot be added');
  const icon = '{1A:080100002460}';
  await setText(area, icon + 'Road');
  await page.$eval('input[type="range"][min="20"]', (el) => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(el, '80'); el.dispatchEvent(new Event('input', { bubbles: true })); });
  await page.$eval(area, (el) => (el as HTMLTextAreaElement).setSelectionRange(0, 0));
  await choose('Red');
  check(await value() === bmgColourCode(0x32) + icon + 'Road', 'colouring preserves inserted icons');
  await shortcut('z'); check(await value() === icon + 'Road', 'undo restores the text before colouring');
  await shortcut('z');
  check(await page.$eval('input[type="range"][min="20"]', (el) => (el as HTMLInputElement).value) === '100', 'font size uses the same undo history');
  await shortcut('y'); await shortcut('y');
  check(await value() === bmgColourCode(0x32) + icon + 'Road', 'redo restores both font size and native colour');
  await page.$eval(area, (el) => { const t = el as HTMLTextAreaElement; t.focus(); t.setSelectionRange(4, 8); });
  await shortcut('x'); check(await value() === icon + 'Road', 'cutting part of a BMG tag expands to the complete code');
  await shortcut('v'); check(await value() === bmgColourCode(0x32) + icon + 'Road', 'clipboard retains the complete BMG code');
  await page.click('input[aria-label="Preview in game screen"]');
  await page.waitForSelector('canvas[data-preview-state="font"]');
  const redPixels = await page.$eval('canvas[role="img"]', (el) => { const c = el as HTMLCanvasElement, d = c.getContext('2d')!.getImageData(0, 0, c.width, c.height).data; let n = 0; for (let p = 0; p < d.length; p += 4) if (d[p] > d[p + 1] + 50 && d[p] > d[p + 2] + 50 && d[p + 3] > 200) n++; return n; });
  check(redPixels > 20, 'font preview renders the native colour');
  await page.evaluate(() => { ([...document.querySelectorAll('[role="dialog"] button')].find((b) => b.textContent?.trim() === 'Save 1') as HTMLElement).click(); });
  await page.waitForFunction(() => document.body.innerText.includes('Game text saved'));
  const saved = parseBMG(findFile(parseU8(yaz0Decompress(new Uint8Array(await Bun.file(archive).arrayBuffer()))), 'Common.bmg')!.data);
  check(saved.messages.find((m: any) => m.id === 0x245c)?.text === setFontSizePercent(bmgColourCode(0x32) + icon + 'Road', 80), 'saved BMG retains the native colour, font size and complete icon code');
  check(saved.messages.find((m: any) => m.id === 0x2455)?.text === 'Moo Moo Meadows', 'saving leaves other messages unchanged');
  check(!errors.length, 'no browser errors');
} finally {
  await browser?.close(); worker.terminate();
  if (!resolve(temp).startsWith(resolve(tmpdir()) + sep)) throw Error('Unsafe test cleanup');
  rmSync(temp, { recursive: true, force: true });
}
